//! [`CanBackend`] implementation on top of Vector's XL-API.
//!
//! Deliberately hardware-model-agnostic: the XL-API itself is the
//! abstraction over Vector's whole VN-series (and related) product line, so
//! this single implementation works with any device the installed XL
//! Driver Library/driver supports -- selection of *which* physical device
//! is entirely a matter of the `selector` (an XL-API application channel
//! index, configured once via Vector Hardware Config/Manager) passed in
//! [`ChannelParams`], not something this code needs to special-case per
//! device.
//!
//! # Validation note
//! The exact struct layout of `XLevent`/`s_xl_can_msg` is generated by
//! `bindgen` from the vendor's `vxlapi.h` at build time (see `ffi.rs`), so
//! field access below must be checked against the actual generated bindings
//! for the SDK version in use before running against real hardware --
//! Vector's XL-API has evolved its event struct across versions (classic
//! CAN vs. CAN FD "compact" events in particular).

use async_trait::async_trait;
use cand_relay_core::{BackendError, CanBackend, ChannelParams, FdParams, FdTxMode, RawCanFrame};
use thiserror::Error;

use crate::{
    ffi,
    timing::{compute_fd_timing, dlc_to_len, len_to_dlc},
};

const APP_NAME: &[u8] = b"cand-relay\0";
pub(crate) const RX_QUEUE_SIZE: u32 = 256;

#[derive(Debug, Error)]
pub enum VectorError {
    #[error("XL-API call '{0}' failed with status {1}")]
    Status(&'static str, i16),
    #[error(
        "invalid channel selector '{0}': expected an XL-API channel index (e.g. \"2\") or the \
         exact channel name reported by `list-devices` (e.g. \"VN5610A Channel 3\")"
    )]
    InvalidSelector(String),
}

pub(crate) fn check(name: &'static str, status: ffi::XLstatus) -> Result<(), VectorError> {
    if i32::from(status) == ffi::XL_SUCCESS as i32 {
        Ok(())
    } else {
        Err(VectorError::Status(name, status))
    }
}

/// Resolves a `selector` string against the channels enumerated by
/// `xlGetDriverConfig` (independent of any application assignment made via
/// Vector Hardware Manager/Config), by either global channel index (e.g.
/// `"2"`) or exact channel name (e.g. `"VN5610A Channel 3"`) -- both as
/// reported by `cand-relay list-devices --backend vector`. Requires the
/// XL-API driver to already be open (`xlOpenDriver`).
///
/// Shared between [`VectorBackend::open`] (for CAN channels) and the
/// wake-up pulser in `wakeup.rs` (for DAIO/Activation Line channels) -- the
/// resolution logic itself doesn't care what kind of channel it is.
///
/// # Safety
/// The XL-API driver must already be open via `xlOpenDriver`.
pub(crate) unsafe fn resolve_access_mask(selector: &str) -> Result<ffi::XLaccess, VectorError> {
    let mut driver_config: ffi::XLdriverConfig = std::mem::zeroed();
    check(
        "xlGetDriverConfig",
        ffi::xlGetDriverConfig(&raw mut driver_config),
    )?;

    let channel_count = { driver_config.channelCount };
    let channels = (0..channel_count as usize).map(|i| driver_config.channel[i]);
    let matches = |ch: &ffi::XLchannelConfig| -> bool {
        if let Ok(channel_index) = selector.parse::<u32>() {
            return u32::from(ch.channelIndex) == channel_index;
        }
        std::ffi::CStr::from_ptr(ch.name.as_ptr()).to_string_lossy() == selector
    };
    channels
        .filter(|ch| matches(ch))
        .map(|ch| ch.channelMask)
        .next()
        .ok_or_else(|| VectorError::InvalidSelector(selector.to_string()))
}

// XL-API CAN FD event tags and FD config options, taken from the
// bindgen-generated bindings (vxlapi.h `#define`s them with casts, which
// bindgen resolves via `clang_macro_fallback`; see build.rs). Narrowed to the
// field widths used by the XL-API structs.
#[allow(
    clippy::cast_possible_truncation,
    reason = "values fit the XL-API field widths"
)]
mod consts {
    use crate::ffi;
    pub(super) const XL_CAN_EV_TAG_RX_OK: u16 = ffi::XL_CAN_EV_TAG_RX_OK as u16;
    pub(super) const XL_CAN_EV_TAG_RX_ERROR: u16 = ffi::XL_CAN_EV_TAG_RX_ERROR as u16;
    pub(super) const XL_CAN_EV_TAG_TX_ERROR: u16 = ffi::XL_CAN_EV_TAG_TX_ERROR as u16;
    pub(super) const XL_CAN_EV_TAG_TX_OK: u16 = ffi::XL_CAN_EV_TAG_TX_OK as u16;
    pub(super) const XL_CAN_EV_TAG_CHIP_STATE: u16 = ffi::XL_CAN_EV_TAG_CHIP_STATE as u16;
    pub(super) const XL_CAN_EV_TAG_TX_MSG: u16 = ffi::XL_CAN_EV_TAG_TX_MSG as u16;
    pub(super) const CANFD_CONFOPT_NO_ISO: u8 = ffi::CANFD_CONFOPT_NO_ISO as u8;
}
use consts::{
    CANFD_CONFOPT_NO_ISO, XL_CAN_EV_TAG_CHIP_STATE, XL_CAN_EV_TAG_RX_ERROR, XL_CAN_EV_TAG_RX_OK,
    XL_CAN_EV_TAG_TX_ERROR, XL_CAN_EV_TAG_TX_MSG, XL_CAN_EV_TAG_TX_OK,
};

/// A single logical CAN channel opened on a Vector device via XL-API.
pub struct VectorBackend {
    driver_opened: bool,
    port_handle: ffi::XLportHandle,
    access_mask: ffi::XLaccess,
    /// Set when the channel was opened in CAN FD mode (XL-API interface
    /// version V4, `xlCanTransmitEx`/`xlCanReceive`); otherwise the classic
    /// `xlCanTransmit`/`xlReceive` path is used.
    fd: Option<FdParams>,
    /// Number of non-data (error/overrun/TX-echo) events seen back-to-back
    /// in [`recv`](CanBackend::recv) without a real data frame in between.
    /// Used to detect and back off from a runaway error-frame storm (e.g. a
    /// transmit that nobody on the bus ever ACKs, which makes the
    /// controller retry as fast as it can, generating an error event per
    /// retry) instead of spinning the async task at full CPU forever.
    consecutive_non_data_events: u32,
}

impl Default for VectorBackend {
    fn default() -> Self {
        Self {
            driver_opened: false,
            port_handle: ffi::XL_INVALID_PORTHANDLE as ffi::XLportHandle,
            access_mask: 0,
            fd: None,
            consecutive_non_data_events: 0,
        }
    }
}

impl VectorBackend {
    pub fn new() -> Self {
        Self::default()
    }

    /// Bookkeeping for a non-data event; backs off once a storm of them is
    /// detected (see [`Self::consecutive_non_data_events`]).
    async fn on_non_data_event(&mut self) {
        // A transmit that nobody on the bus ACKs (e.g. no other node
        // present/awake, wrong bitrate/FD settings, or a wiring issue) makes
        // the controller retry as fast as it can, which otherwise shows up
        // as an unbounded, unthrottled stream of error events -- pinning
        // this task (and a CPU core) at 100% forever. Detect the pattern
        // and back off with an increasing sleep, capped at 250ms, logging a
        // hint once per storm.
        self.consecutive_non_data_events += 1;
        const WARN_AFTER: u32 = 200;
        if self.consecutive_non_data_events == WARN_AFTER {
            tracing::warn!(
                "received {WARN_AFTER}+ consecutive non-data CAN events (errors/overrun/tx \
                 echoes) with no actual data frame in between -- this usually means a transmit is \
                 going unacknowledged (no other/awake node on the bus, wrong bitrate or CAN FD \
                 settings, or a wiring/termination problem), not a bridge bug. Backing off to \
                 avoid spinning the CPU; frames will still be relayed normally once real traffic \
                 resumes."
            );
        }
        if self.consecutive_non_data_events >= WARN_AFTER {
            let backoff_ms = (self.consecutive_non_data_events - WARN_AFTER).clamp(1, 250);
            tokio::time::sleep(std::time::Duration::from_millis(u64::from(backoff_ms))).await;
        }
    }

    /// # Safety
    /// `port_handle`/`access_mask` must refer to a port opened with
    /// `XL_INTERFACE_VERSION_V4` that has init access to the channel.
    unsafe fn configure_fd(
        port_handle: ffi::XLportHandle,
        access_mask: ffi::XLaccess,
        params: &ChannelParams,
        fd: &FdParams,
    ) -> Result<(), BackendError> {
        let arb_sp = params.sample_point.unwrap_or(80);
        let timing = compute_fd_timing(
            params.bitrate,
            arb_sp,
            fd.data_bitrate,
            fd.data_sample_point,
        )
        .ok_or_else(|| {
            BackendError::Open(format!(
                "no valid CAN FD bit timing for {} bit/s @ {arb_sp}% / {} bit/s @ {}% with an {} \
                 Hz controller clock",
                params.bitrate,
                fd.data_bitrate,
                fd.data_sample_point,
                crate::timing::CAN_FD_CLOCK_HZ
            ))
        })?;
        let mut conf: ffi::XLcanFdConf = std::mem::zeroed();
        conf.arbitrationBitRate = timing.arbitration.bitrate;
        conf.sjwAbr = timing.arbitration.sjw;
        conf.tseg1Abr = timing.arbitration.tseg1;
        conf.tseg2Abr = timing.arbitration.tseg2;
        conf.dataBitRate = timing.data.bitrate;
        conf.sjwDbr = timing.data.sjw;
        conf.tseg1Dbr = timing.data.tseg1;
        conf.tseg2Dbr = timing.data.tseg2;
        conf.options = if fd.iso { 0 } else { CANFD_CONFOPT_NO_ISO };
        tracing::info!(
            arb_bitrate = timing.arbitration.bitrate,
            arb_sample_point = timing.arbitration.sample_point(),
            arb_tq = timing.arbitration.tq(),
            data_bitrate = timing.data.bitrate,
            data_sample_point = timing.data.sample_point(),
            data_tq = timing.data.tq(),
            prescaler = timing.prescaler,
            iso = fd.iso,
            "configuring CAN FD channel"
        );
        check(
            "xlCanFdSetConfiguration",
            ffi::xlCanFdSetConfiguration(port_handle, access_mask, &raw mut conf),
        )
        .map_err(|e| BackendError::Open(e.to_string()))
    }

    async fn send_fd(&mut self, frame: RawCanFrame, fd: &FdParams) -> Result<(), BackendError> {
        if frame.data.len() > ffi::XL_CAN_MAX_DATA_LEN as usize {
            return Err(BackendError::Send(format!(
                "frame payload of {} bytes exceeds the CAN FD maximum of 64",
                frame.data.len()
            )));
        }
        let (as_fd, brs) = if frame.fd {
            // Explicit FD request (e.g. `< fdsend >`): honor the given BRS.
            (true, frame.brs)
        } else if frame.data.len() > 8 {
            (true, true)
        } else {
            match fd.tx_mode {
                FdTxMode::FdBrs => (true, true),
                FdTxMode::Fd => (true, false),
                FdTxMode::Classic => (false, false),
            }
        };

        let mut event: ffi::XLcanTxEvent = unsafe { std::mem::zeroed() };
        event.tag = XL_CAN_EV_TAG_TX_MSG;
        event.transId = 0xFFFF;
        // Safety: `canMsg` is the only union variant of XLcanTxEvent.
        let msg = unsafe { &mut event.tagData.canMsg };
        msg.canId = if frame.extended {
            frame.id | ffi::XL_CAN_EXT_MSG_ID
        } else {
            frame.id
        };
        let mut flags = 0;
        if as_fd {
            flags |= ffi::XL_CAN_TXMSG_FLAG_EDL;
            if brs {
                flags |= ffi::XL_CAN_TXMSG_FLAG_BRS;
            }
        }
        msg.msgFlags = flags;
        let dlc = len_to_dlc(frame.data.len());
        msg.dlc = dlc;
        msg.data[..frame.data.len()].copy_from_slice(&frame.data);
        // Pad up to the DLC's length (only relevant for FD lengths that
        // aren't a valid DLC size, e.g. 10 bytes -> 12). Use the ISO-TP
        // conventional 0xCC filler; clients that care about padding
        // should send DLC-sized frames themselves.
        let padded_len = dlc_to_len(dlc);
        msg.data[frame.data.len()..padded_len].fill(0xCC);

        let mut sent: u32 = 0;
        // Safety: `event` is a fully initialized XLcanTxEvent for a single
        // transmit request, as required by xlCanTransmitEx.
        let status = unsafe {
            ffi::xlCanTransmitEx(
                self.port_handle,
                self.access_mask,
                1,
                &raw mut sent,
                &raw mut event,
            )
        };
        check("xlCanTransmitEx", status).map_err(|e| BackendError::Send(e.to_string()))
    }

    async fn recv_fd(&mut self) -> Result<RawCanFrame, BackendError> {
        loop {
            let mut event: ffi::XLcanRxEvent = unsafe { std::mem::zeroed() };
            // Safety: xlCanReceive fills exactly one XLcanRxEvent.
            let status = unsafe { ffi::xlCanReceive(self.port_handle, &raw mut event) };
            if i32::from(status) == ffi::XL_ERR_QUEUE_IS_EMPTY as i32 {
                // No event ready yet; sleep briefly rather than busy-yield
                // (a production implementation should wait on the XL-API
                // notification handle instead of polling).
                tokio::time::sleep(std::time::Duration::from_millis(1)).await;
                continue;
            }
            check("xlCanReceive", status).map_err(|e| BackendError::Receive(e.to_string()))?;

            let tag = event.tag;
            if tag == XL_CAN_EV_TAG_TX_OK {
                // Echo of our own (or another app's, on a shared channel)
                // successful transmit -- proof the frame was ACKed.
                self.consecutive_non_data_events = 0;
                continue;
            }
            if tag != XL_CAN_EV_TAG_RX_OK {
                // Safety: union variants selected by tag per vxlapi.h; all
                // are plain-old-data so reading them is sound regardless.
                let detail = unsafe {
                    match tag {
                        XL_CAN_EV_TAG_RX_ERROR | XL_CAN_EV_TAG_TX_ERROR => {
                            format!("errorCode={}", event.tagData.canError.errorCode)
                        }
                        XL_CAN_EV_TAG_CHIP_STATE => {
                            let s = event.tagData.canChipState;
                            format!(
                                "busStatus={:#04x} txErr={} rxErr={}",
                                s.busStatus, s.txErrorCounter, s.rxErrorCounter
                            )
                        }
                        _ => String::new(),
                    }
                };
                tracing::debug!(
                    tag = format!("{tag:#06x}"),
                    detail,
                    "skipping non-data CAN FD event"
                );
                self.on_non_data_event().await;
                continue;
            }
            self.consecutive_non_data_events = 0;

            // Safety: `tag == XL_CAN_EV_TAG_RX_OK` guarantees `canRxOkMsg`
            // is the active union variant.
            let msg = unsafe { &event.tagData.canRxOkMsg };
            let flags = msg.msgFlags;
            if flags & ffi::XL_CAN_RXMSG_FLAG_EF != 0 {
                // Error frame reported as RX event.
                self.on_non_data_event().await;
                continue;
            }
            let extended = msg.canId & ffi::XL_CAN_EXT_MSG_ID != 0;
            let id = msg.canId & !ffi::XL_CAN_EXT_MSG_ID;
            let fd = flags & ffi::XL_CAN_RXMSG_FLAG_EDL != 0;
            let len = if fd {
                dlc_to_len(msg.dlc)
            } else {
                usize::from(msg.dlc.min(8))
            };
            return Ok(RawCanFrame {
                id,
                extended,
                data: msg.data[..len].to_vec(),
                fd,
                brs: flags & ffi::XL_CAN_RXMSG_FLAG_BRS != 0,
                esi: flags & ffi::XL_CAN_RXMSG_FLAG_ESI != 0,
            });
        }
    }

    async fn send_classic(&mut self, frame: RawCanFrame) -> Result<(), BackendError> {
        if frame.data.len() > 8 {
            return Err(BackendError::Send(format!(
                "frame payload of {} bytes requires CAN FD; configure [bus.fd] for this bus",
                frame.data.len()
            )));
        }
        // XL-API sends are synchronous/non-blocking; no async work happens
        // here, matching the trait signature for interface consistency with
        // other backends.
        let mut event: ffi::XLevent = unsafe { std::mem::zeroed() };
        event.tag = ffi::e_XLevent_type_XL_TRANSMIT_MSG as ffi::XLeventTag;

        // Safety: `tagData.msg` is the active union variant for
        // XL_TRANSMIT_MSG events, matching XL-API's documented usage.
        let msg = unsafe { &mut event.tagData.msg };
        msg.id = if frame.extended {
            frame.id | ffi::XL_CAN_EXT_MSG_ID
        } else {
            frame.id
        };
        msg.dlc = frame.data.len() as u16;
        msg.flags = 0;
        for (i, byte) in frame.data.iter().enumerate() {
            if let Some(slot) = msg.data.get_mut(i) {
                *slot = *byte;
            }
        }

        let mut message_count: u32 = 1;
        // Safety: `event` is a valid, fully initialized XLevent for a single
        // transmit request, as required by xlCanTransmit.
        let status = unsafe {
            ffi::xlCanTransmit(
                self.port_handle,
                self.access_mask,
                &raw mut message_count,
                (&raw mut event).cast(),
            )
        };
        check("xlCanTransmit", status).map_err(|e| BackendError::Send(e.to_string()))
    }

    async fn recv_classic(&mut self) -> Result<RawCanFrame, BackendError> {
        loop {
            let mut event: ffi::XLevent = unsafe { std::mem::zeroed() };
            // Safety: xlReceive fills exactly one XLevent per call given a
            // zeroed, appropriately sized buffer.
            let mut event_count: u32 = 1;
            let status =
                unsafe { ffi::xlReceive(self.port_handle, &raw mut event_count, &raw mut event) };

            if i32::from(status) == ffi::XL_ERR_QUEUE_IS_EMPTY as i32 {
                // No frame ready yet; yield so this doesn't spin the async
                // runtime. A production implementation should instead wait
                // on the XL-API notification handle/event object for the
                // port rather than polling.
                tokio::task::yield_now().await;
                continue;
            }
            check("xlReceive", status).map_err(|e| BackendError::Receive(e.to_string()))?;

            if u32::from(event.tag) != ffi::e_XLevent_type_XL_RECEIVE_MSG as u32 {
                continue;
            }

            // Safety: `tag == XL_RECEIVE_MSG` guarantees `tagData.msg` is
            // the active union variant.
            let msg = unsafe { &event.tagData.msg };

            // Skip anything that isn't an actual received data frame: bus
            // error frames, overrun indications, TX echoes/requests, etc.
            // all share XL_RECEIVE_MSG's tag but carry no real payload --
            // forwarding them as if they were data frames on the wire would
            // be misleading to clients (e.g. spurious high-rate frames with
            // a fixed/garbage ID during a bitrate mismatch or unterminated
            // bus).
            let flags = msg.flags;
            if flags
                & (ffi::XL_CAN_MSG_FLAG_ERROR_FRAME
                    | ffi::XL_CAN_MSG_FLAG_OVERRUN
                    | ffi::XL_CAN_MSG_FLAG_TX_COMPLETED
                    | ffi::XL_CAN_MSG_FLAG_TX_REQUEST) as u16
                != 0
            {
                let id = msg.id;
                tracing::debug!(
                    flags = format!("{flags:#04x}"),
                    id,
                    "skipping non-data CAN event"
                );
                self.on_non_data_event().await;
                continue;
            }
            self.consecutive_non_data_events = 0;

            let extended = msg.id & ffi::XL_CAN_EXT_MSG_ID != 0;
            let id = msg.id & !ffi::XL_CAN_EXT_MSG_ID;
            let len = usize::from(msg.dlc).min(msg.data.len());
            return Ok(RawCanFrame {
                id,
                extended,
                data: msg.data[..len].to_vec(),
                ..Default::default()
            });
        }
    }
}

#[async_trait]
impl CanBackend for VectorBackend {
    async fn open(&mut self, params: &ChannelParams) -> Result<(), BackendError> {
        // Safety: all calls below follow the XL-API's documented
        // open/activate sequence; pointers passed are to locals that
        // outlive the call, per the API's synchronous, non-retained-pointer
        // contract.
        unsafe {
            check("xlOpenDriver", ffi::xlOpenDriver())
                .map_err(|e| BackendError::Open(e.to_string()))?;
            self.driver_opened = true;

            let access_mask = resolve_access_mask(&params.selector)
                .map_err(|e| BackendError::Open(e.to_string()))?;
            self.access_mask = access_mask;

            let interface_version = if params.fd.is_some() {
                ffi::XL_INTERFACE_VERSION_V4
            } else {
                ffi::XL_INTERFACE_VERSION
            };
            let mut permission_mask: ffi::XLaccess = access_mask;
            let mut port_handle: ffi::XLportHandle = 0;
            check(
                "xlOpenPort",
                ffi::xlOpenPort(
                    &raw mut port_handle,
                    APP_NAME.as_ptr().cast_mut().cast(),
                    access_mask,
                    &raw mut permission_mask,
                    RX_QUEUE_SIZE,
                    interface_version,
                    ffi::XL_BUS_TYPE_CAN,
                ),
            )
            .map_err(|e| BackendError::Open(e.to_string()))?;
            self.port_handle = port_handle;
            self.fd = params.fd.clone();

            if permission_mask == access_mask {
                match &params.fd {
                    Some(fd) => Self::configure_fd(port_handle, access_mask, params, fd)?,
                    None => check(
                        "xlCanSetChannelBitrate",
                        ffi::xlCanSetChannelBitrate(port_handle, access_mask, params.bitrate),
                    )
                    .map_err(|e| BackendError::Open(e.to_string()))?,
                }
            } else {
                // We didn't get "init access" for this channel -- someone
                // else (another open port, e.g. DTS Monaco/CANoe, or a stale
                // one left behind by a process that didn't call
                // xlClosePort/xlCloseDriver on exit) already holds it. Bus
                // parameters can't be set without init access, so the
                // channel keeps running with whatever its current owner
                // configured. Sharing the channel this way is fine (and
                // useful for sniffing alongside another tool) as long as the
                // owner configured the same mode -- in particular a CAN FD
                // owner + a classic-mode port here won't see FD traffic.
                tracing::warn!(
                    requested_bitrate = params.bitrate,
                    fd = params.fd.is_some(),
                    access_mask,
                    permission_mask,
                    "did not get init access for this Vector channel; bus parameters were NOT \
                     applied -- the channel is running with whatever its current owner (e.g. \
                     another open port, DTS Monaco, CANoe, or a stale port from a previously \
                     killed process) configured."
                );
            }

            check(
                "xlActivateChannel",
                ffi::xlActivateChannel(port_handle, access_mask, ffi::XL_BUS_TYPE_CAN, 0),
            )
            .map_err(|e| BackendError::Open(e.to_string()))?;
        }

        Ok(())
    }

    async fn send(&mut self, frame: RawCanFrame) -> Result<(), BackendError> {
        match self.fd.clone() {
            Some(fd) => self.send_fd(frame, &fd).await,
            None => self.send_classic(frame).await,
        }
    }

    async fn recv(&mut self) -> Result<RawCanFrame, BackendError> {
        if self.fd.is_some() {
            self.recv_fd().await
        } else {
            self.recv_classic().await
        }
    }

    async fn close(&mut self) -> Result<(), BackendError> {
        if self.port_handle != ffi::XL_INVALID_PORTHANDLE as ffi::XLportHandle {
            unsafe {
                let _ = ffi::xlDeactivateChannel(self.port_handle, self.access_mask);
                let _ = ffi::xlClosePort(self.port_handle);
            }
            self.port_handle = ffi::XL_INVALID_PORTHANDLE as ffi::XLportHandle;
        }
        if self.driver_opened {
            unsafe {
                ffi::xlCloseDriver();
            }
            self.driver_opened = false;
        }
        self.fd = None;
        Ok(())
    }
}
